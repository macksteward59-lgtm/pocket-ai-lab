import Foundation
import XCTest
@testable import PocketLlamaEngine

/// Narrow integration proof. The engine below deliberately supplies a fixture,
/// NOT actual llama.cpp inference or permission to transfer latent blobs.
final class NativeGIECaptureEncoderTests: XCTestCase {
    private struct CodebookFixture: Decodable {
        let artifactHex: String
        let sha256: String
        let modelId: String
        let modelRevision: String
    }

    private struct SequenceFixture: Decodable {
        let tokenCount: Int
        let embeddingDimension: Int
        let tokenEmbeddings: [Float]
        let payloadHex: String
        let payloadByteLength: Int
        let segmentTokenCounts: [Int]
        let decodedSegmentEmbeddings: [Float]
    }

    private func fixture<T: Decodable>(_ name: String) throws -> T {
        let url = try XCTUnwrap(Bundle.module.url(forResource: name, withExtension: "json"))
        return try JSONDecoder().decode(T.self, from: Data(contentsOf: url))
    }

    private func data(hex: String) throws -> Data {
        guard hex.count.isMultiple(of: 2) else { throw GIEFixtureError.invalidHex }
        var result = Data()
        var index = hex.startIndex
        while index < hex.endIndex {
            let next = hex.index(index, offsetBy: 2)
            guard let value = UInt8(hex[index..<next], radix: 16) else {
                throw GIEFixtureError.invalidHex
            }
            result.append(value)
            index = next
        }
        return result
    }

    func testNativeSequenceGenerationUsesExactLeaseAndVerifiedGCB1BeforeEncoding() async throws {
        let artifact: CodebookFixture = try fixture("gie-codebook-artifact-v1")
        let sample: SequenceFixture = try fixture("gie-verified-sequence-v1")
        let id = NativeLatentModelIdentity(modelId: artifact.modelId, modelRevision: artifact.modelRevision)
        let bytes = try data(hex: artifact.artifactHex)
        let engine = FixtureSequenceEngine(
            output: LlamaLatentSequenceOutput(
                modelId: artifact.modelId,
                text: "fixture text, not generated by a GGUF",
                embeddings: sample.tokenEmbeddings,
                tokenCount: sample.tokenCount,
                embeddingDimension: sample.embeddingDimension
            )
        )
        let runtime = try NativeInferenceRuntime(
            engine: engine,
            poolConfiguration: try ModelPoolConfiguration(
                maxResidentMemoryMB: 1024,
                maxLoadedModels: 1,
                minimumFreeMemoryMB: 0
            ),
            availableMemoryMB: { 2048 },
            maxConcurrentRequests: 1
        )
        let model = ModelDescriptor(
            id: artifact.modelId, name: "synthetic test-only model",
            path: "/tmp/not-a-loaded-real-model.gguf", contextLength: 512
        )
        let lease = try await runtime.acquire(model: model, estimatedMemoryMB: 128)
        let request = GenerationRequest(prompt: "Synthetic sequence", maxTokens: 5, temperature: 0)
        let codebook = try NativeGIECodebookArtifact.load(
            bytes, expectedSHA256: artifact.sha256, expectedModelIdentity: id
        )
        let minimumPayloadBytes = try NativeGIESequenceEncoder(codebook: codebook).minimumPayloadByteLength
        XCTAssertEqual(minimumPayloadBytes, 53, "The fixture requires a 50-byte header, one span and one index.")

        // Wrong model identity or corrupted canonical artifact must be rejected
        // before the injected engine is ever called.
        do {
            _ = try await NativeGIECaptureEncoder.generate(
                runtime: runtime, lease: lease, request: request,
                expectedModelIdentity: NativeLatentModelIdentity(
                    modelId: "wrong-model", modelRevision: id.modelRevision
                ),
                codebookArtifact: bytes,
                expectedCodebookSHA256: artifact.sha256
            )
            XCTFail("Foreign model should be rejected")
        } catch NativeGIECaptureError.modelIdentityMismatch {
        }
        do {
            _ = try await NativeGIECaptureEncoder.generate(
                runtime: runtime, lease: lease, request: request,
                expectedModelIdentity: id,
                codebookArtifact: bytes,
                expectedCodebookSHA256: String(repeating: "a", count: 64)
            )
            XCTFail("Wrong codebook digest should be rejected")
        } catch NativeGIESequenceCodecError.codebookMismatch {
        }
        do {
            _ = try await NativeGIECaptureEncoder.generate(
                runtime: runtime, lease: lease, request: request,
                expectedModelIdentity: id, codebookArtifact: bytes,
                expectedCodebookSHA256: artifact.sha256,
                maxPayloadBytes: minimumPayloadBytes - 1
            )
            XCTFail("A budget smaller than any nonempty GIE1 frame should fail before inference")
        } catch NativeGIECaptureError.payloadTooLarge {
        }
        let callsBeforeGeneration = await engine.sequenceCalls()
        XCTAssertEqual(callsBeforeGeneration, 0)
        let schedulerBeforeGeneration = await runtime.schedulerSnapshot()
        XCTAssertEqual(schedulerBeforeGeneration.activeRequests, 0)
        XCTAssertEqual(schedulerBeforeGeneration.waitingRequests, 0)

        let encoded = try await NativeGIECaptureEncoder.generate(
            runtime: runtime, lease: lease, request: request,
            expectedModelIdentity: id,
            codebookArtifact: bytes,
            expectedCodebookSHA256: artifact.sha256,
            maxLatentTokens: 5
        )
        let callsAfterGeneration = await engine.sequenceCalls()
        XCTAssertEqual(callsAfterGeneration, 1)
        XCTAssertEqual(encoded.providerKind, .other, "Fixture engines cannot impersonate llama.cpp")
        XCTAssertEqual(encoded.modelIdentity, id)
        XCTAssertEqual(encoded.text, "fixture text, not generated by a GGUF")
        XCTAssertEqual(encoded.tokenCount, sample.tokenCount)
        XCTAssertEqual(encoded.embeddingDimension, sample.embeddingDimension)
        XCTAssertEqual(encoded.payloadByteLength, sample.payloadByteLength)
        XCTAssertEqual(encoded.payload, try data(hex: sample.payloadHex))
        let decoded = try NativeGIESequenceCodec(codebook: codebook).decode(
            encoded.payload, modelIdentity: id
        )
        XCTAssertEqual(decoded.segmentTokenCounts, sample.segmentTokenCounts)
        XCTAssertEqual(decoded.segmentEmbeddings, sample.decodedSegmentEmbeddings)

        // This budget can hold one segment, so it must be admitted; the actual
        // five-token result needs two segments and must still fail after capture.
        do {
            _ = try await NativeGIECaptureEncoder.generate(
                runtime: runtime, lease: lease, request: request,
                expectedModelIdentity: id, codebookArtifact: bytes,
                expectedCodebookSHA256: artifact.sha256,
                maxPayloadBytes: minimumPayloadBytes
            )
            XCTFail("Actual multi-segment payload should exceed the admitted minimum budget")
        } catch NativeGIECaptureError.payloadTooLarge {
        }
        let callsAfterEncodingFailure = await engine.sequenceCalls()
        XCTAssertEqual(callsAfterEncodingFailure, 2)
        let pool = await runtime.snapshot()
        XCTAssertEqual(pool.activeUseCount, 0)
        XCTAssertEqual(pool.activeLeaseCount, 1)
        let schedulerAfterFailure = await runtime.schedulerSnapshot()
        XCTAssertEqual(schedulerAfterFailure.activeRequests, 0)
        XCTAssertEqual(schedulerAfterFailure.waitingRequests, 0)
        let released = await runtime.release(lease)
        XCTAssertTrue(released)
        try await runtime.unload(modelId: model.id)
    }

    func testCanonicalIdentityRejectsDecomposedLeaseAndCapturedModelId() async throws {
        let identity = NativeLatentModelIdentity(modelId: "model-caf\u{e9}", modelRevision: "revision-1")
        let decomposedId = "model-cafe\u{301}"
        let artifact = try GIECodebookTestSupport.artifact(
            modelId: identity.modelId, modelRevision: identity.modelRevision, embeddingDimension: 2
        )
        let captured = LlamaLatentSequenceOutput(
            modelId: decomposedId, text: "synthetic", embeddings: [-1, 1],
            tokenCount: 1, embeddingDimension: 2
        )
        let engine = FixtureSequenceEngine(output: captured)
        let runtime = try NativeInferenceRuntime(
            engine: engine,
            poolConfiguration: try ModelPoolConfiguration(
                maxResidentMemoryMB: 1024, maxLoadedModels: 1, minimumFreeMemoryMB: 0
            ),
            availableMemoryMB: { 2048 }, maxConcurrentRequests: 1
        )
        let model = ModelDescriptor(
            id: decomposedId, name: "Unicode fixture", path: "/tmp/not-a-loaded-real-model.gguf",
            contextLength: 512
        )
        let lease = try await runtime.acquire(model: model, estimatedMemoryMB: 128)
        do {
            _ = try await NativeGIECaptureEncoder.generate(
                runtime: runtime, lease: lease,
                request: GenerationRequest(prompt: "Unicode fixture", maxTokens: 1, temperature: 0),
                expectedModelIdentity: identity, codebookArtifact: artifact,
                expectedCodebookSHA256: GIECodebookTestSupport.sha256(artifact)
            )
            XCTFail("Canonically equivalent lease IDs must not satisfy an exact byte identity")
        } catch NativeGIECaptureError.modelIdentityMismatch {
        }
        let calls = await engine.sequenceCalls()
        XCTAssertEqual(calls, 0)
        XCTAssertThrowsError(try NativeGIECaptureEncoder.encodeCaptured(
            captured, expectedModelIdentity: identity, codebookArtifact: artifact,
            expectedCodebookSHA256: GIECodebookTestSupport.sha256(artifact)
        )) { XCTAssertEqual($0 as? NativeGIECaptureError, .modelIdentityMismatch) }
        let pool = await runtime.snapshot()
        XCTAssertEqual(pool.activeUseCount, 0)
        let released = await runtime.release(lease)
        XCTAssertTrue(released)
        try await runtime.unload(modelId: model.id)
    }

    func testCapturedOutputRejectsWrongIdentityShapeNonFiniteAndPayloadBudget() throws {
        let artifact: CodebookFixture = try fixture("gie-codebook-artifact-v1")
        let sample: SequenceFixture = try fixture("gie-verified-sequence-v1")
        let id = NativeLatentModelIdentity(modelId: artifact.modelId, modelRevision: artifact.modelRevision)
        let bytes = try data(hex: artifact.artifactHex)
        func captured(_ model: String, _ vectors: [Float], _ count: Int, _ dimension: Int) -> LlamaLatentSequenceOutput {
            LlamaLatentSequenceOutput(
                modelId: model,
                text: "synthetic",
                embeddings: vectors,
                tokenCount: count,
                embeddingDimension: dimension
            )
        }
        let good = captured(artifact.modelId, sample.tokenEmbeddings, sample.tokenCount, sample.embeddingDimension)
        XCTAssertThrowsError(try NativeGIECaptureEncoder.encodeCaptured(
            captured("another", sample.tokenEmbeddings, sample.tokenCount, sample.embeddingDimension),
            expectedModelIdentity: id, codebookArtifact: bytes, expectedCodebookSHA256: artifact.sha256
        )) { XCTAssertEqual($0 as? NativeGIECaptureError, .modelIdentityMismatch) }
        XCTAssertThrowsError(try NativeGIECaptureEncoder.encodeCaptured(
            captured(artifact.modelId, sample.tokenEmbeddings, 6, sample.embeddingDimension),
            expectedModelIdentity: id, codebookArtifact: bytes, expectedCodebookSHA256: artifact.sha256
        )) { XCTAssertEqual($0 as? NativeGIECaptureError, .invalidCaptureBounds) }
        var invalid = sample.tokenEmbeddings
        invalid[0] = Float.nan
        XCTAssertThrowsError(try NativeGIECaptureEncoder.encodeCaptured(
            captured(artifact.modelId, invalid, sample.tokenCount, sample.embeddingDimension),
            expectedModelIdentity: id, codebookArtifact: bytes, expectedCodebookSHA256: artifact.sha256
        )) { XCTAssertEqual($0 as? NativeGIECaptureError, .invalidCaptureBounds) }
        XCTAssertThrowsError(try NativeGIECaptureEncoder.encodeCaptured(
            good, expectedModelIdentity: id, codebookArtifact: bytes,
            expectedCodebookSHA256: artifact.sha256, maxPayloadBytes: 1
        )) { XCTAssertEqual($0 as? NativeGIECaptureError, .payloadTooLarge) }
        let output = try NativeGIECaptureEncoder.encodeCaptured(
            good, expectedModelIdentity: id, codebookArtifact: bytes,
            expectedCodebookSHA256: artifact.sha256
        )
        XCTAssertEqual(output.providerKind, .other)
        XCTAssertEqual(output.payload, try data(hex: sample.payloadHex))
    }

    private enum GIEFixtureError: Error { case invalidHex }
}

private actor FixtureSequenceEngine: LatentSequenceExportingLlamaEngine {
    private let output: LlamaLatentSequenceOutput
    private var calls = 0

    init(output: LlamaLatentSequenceOutput) {
        self.output = output
    }

    func load(model: ModelDescriptor) async throws -> RuntimeSession {
        RuntimeSession(id: UUID().uuidString, modelId: model.id)
    }

    func generate(session: RuntimeSession, request: GenerationRequest) async throws -> AsyncThrowingStream<Token, Error> {
        throw LlamaEngineError.backendUnavailable("This test engine cannot generate text")
    }

    func generateWithLatent(session: RuntimeSession, request: GenerationRequest) async throws -> LlamaLatentOutput {
        throw LlamaEngineError.backendUnavailable("This test engine cannot export a final-token embedding")
    }

    func generateWithLatentSequence(
        session: RuntimeSession, request: GenerationRequest,
        maxLatentTokens: Int, maxLatentBytes: Int
    ) async throws -> LlamaLatentSequenceOutput {
        calls += 1
        return output
    }

    func cancel(sessionId: String, requestId: String) async {}
    func cancelAndWait(sessionId: String, requestId: String) async {}
    func unload(sessionId: String) async {}
    func sequenceCalls() -> Int { calls }
}
